/**
 * Copies the kit's verbatim legal text (docs/source/tt-forms/content/*.md) into a TS module so it ships
 * with the server bundle. Run after the kit content changes:  pnpm build:content
 * tests/unit/content.test.ts fails if the generated module drifts from the source files.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'docs/source/tt-forms/content');
const entries = readdirSync(dir)
  .filter((f) => f.endsWith('.md'))
  .sort()
  .map((f) => `  ${JSON.stringify(`content/${f}`)}: ${JSON.stringify(readFileSync(path.join(dir, f), 'utf8'))},`);

writeFileSync(
  path.join(root, 'lib/spec/content.generated.ts'),
  `// GENERATED by scripts/build-content.ts from docs/source/tt-forms/content. Do not edit by hand.\n` +
    `// Verbatim legal text: typos are intentional.\n` +
    `export const CONTENT: Record<string, string> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`wrote ${entries.length} content blocks`);
